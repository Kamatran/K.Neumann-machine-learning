"""W0: a simulated training loop recorded in MLflow.

There is no model here. The curves are generated by formulas with random noise, so that you can
learn the MLflow vocabulary (run, parameter, metric with steps, artifact) before the first real
model in W1. The shape mimics real training: the loss falls, the accuracy rises towards a plateau,
and a too-large learning rate makes the curves noisy.

Usage (from the root of your project repository, with the MLflow server running):
    uv run python exercises/w00/simulated_training.py --lr 0.01
    uv run python exercises/w00/simulated_training.py --lr 0.05 --steps 100
"""

import argparse

import mlflow
import numpy as np

from mlproject.tracking import setup

ACC_START, ACC_PLATEAU = 0.80, 0.93  # accuracy curve: start and plateau
ACC_LOW, ACC_HIGH = 0.80, 0.95  # reported accuracy stays in this range
LOSS_START, LOSS_MIN = 2.3, 0.3


def simulate_step(step: int, lr: float, rng: np.random.Generator) -> tuple[float, float]:
    """Return (train_loss, val_accuracy) after `step` steps. Not a model: formulas plus noise."""
    progress = 1 - np.exp(-2 * lr * step)  # 0 at the start, towards 1 with more steps
    noise = 0.005 * lr / 0.05  # a larger learning rate gives noisier curves
    train_loss = LOSS_MIN + (LOSS_START - LOSS_MIN) * (1 - progress) + rng.normal(0, 3 * noise)
    val_accuracy = ACC_START + (ACC_PLATEAU - ACC_START) * progress + rng.normal(0, noise)
    return max(train_loss, 0.0), float(np.clip(val_accuracy, ACC_LOW, ACC_HIGH))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--steps", type=int, default=50, help="number of training steps (default: 50)")
    parser.add_argument("--lr", type=float, default=0.05, help="simulated learning rate (default: 0.05)")
    parser.add_argument("--seed", type=int, default=42, help="random seed of the noise (default: 42)")
    args = parser.parse_args()

    setup("w00-simulated-training")
    rng = np.random.default_rng(args.seed)

    with mlflow.start_run(run_name=f"lr-{args.lr}-steps-{args.steps}"):
        mlflow.log_params({"steps": args.steps, "lr": args.lr, "seed": args.seed})

        best_acc, best_step = 0.0, 0
        for step in range(1, args.steps + 1):
            train_loss, val_accuracy = simulate_step(step, args.lr, rng)
            mlflow.log_metrics({"train_loss": train_loss, "val_accuracy": val_accuracy}, step=step)
            if val_accuracy > best_acc:
                best_acc, best_step = val_accuracy, step

        mlflow.log_metric("best_val_accuracy", best_acc)
        mlflow.set_tag("note", "simulation, no model")

        summary = (
            f"steps: {args.steps}\nlr: {args.lr}\nseed: {args.seed}\n"
            f"final train_loss: {train_loss:.4f}\nfinal val_accuracy: {val_accuracy:.4f}\n"
            f"best val_accuracy: {best_acc:.4f} at step {best_step}\n"
        )
        mlflow.log_text(summary, "summary.txt")  # the artifact: a small text file attached to the run

    print(f"lr={args.lr:<5} steps={args.steps:<4} final train_loss {train_loss:.4f}, "
          f"final val_accuracy {val_accuracy:.4f}, best {best_acc:.4f} at step {best_step}")


if __name__ == "__main__":
    main()
